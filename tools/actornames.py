#!/usr/bin/env python3
"""Write src/ootgz/actornames.c: the actors debug > actors > spawn by name offers (FINDINGS 9.29).

    python3 tools/actornames.py <1.0.0 .nup> <1.1.1 .nup>

An actor can be made if the game has its pack, romfs/Pack/Actor/<name>.pack.zs. Only the enemies, NPCs, objects
and items (Enemy_, Npc_, Obj_, Item_) are offered, and only those both game versions have, sorted by name.
"""
import os
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

KINDS = ("Enemy_", "Npc_", "Obj_", "Item_")
PREFIX = "romfs/Pack/Actor/"
SUFFIX = ".pack.zs"
OUT = Path(__file__).resolve().parents[1] / "src" / "ootgz" / "actornames.c"


def names(nup_path):
    import nupfs

    nup = nupfs.Nup(nup_path)
    found = set()
    for path, _record in nup.walk():
        if path.startswith(PREFIX) and path.endswith(SUFFIX):
            name = path[len(PREFIX):-len(SUFFIX)]
            if name.startswith(KINDS) and "/" not in name:
                found.add(name)
    return found


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    both = sorted(names(sys.argv[1]) & names(sys.argv[2]))
    if not both:
        sys.exit("no actor packs found: check the .nup paths")
    lines = [
        "/* Generated by tools/actornames.py: the actors both game versions have a pack for (romfs/Pack/Actor),",
        " * enemies, NPCs, objects and items, by name. debug > actors > spawn by name (FINDINGS 9.29). */",
        '#include "actornames.h"',
        "",
        "const char *const actor_names[] = {",
    ]
    lines += [f'  "{n}",' for n in both]
    lines += ["};", "const int actor_names_count = sizeof(actor_names) / sizeof(*actor_names);", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{OUT}: {len(both)} actors")


if __name__ == "__main__":
    main()
